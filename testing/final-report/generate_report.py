import os, csv, re
from datetime import datetime
from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

# Paths
base_dir = os.path.abspath(os.path.dirname(__file__))
report_docx_path = os.path.join(base_dir, 'Ozone_Mall_Software_Testing_Report_v2.docx')
report_pdf_path = os.path.join(base_dir, 'Ozone_Mall_Software_Testing_Report_v2.pdf')

def add_heading(doc, text, level=1):
    doc.add_heading(text, level=level)

def extract_test_cases():
    """Parse Playwright spec files to collect test case IDs and brief descriptions.
    Returns a list of dicts with keys: id, module, scenario.
    """
    specs_dir = os.path.abspath(os.path.join(base_dir, '..', 'playwright'))
    test_cases = []
    pattern = re.compile(r"test\(['\"](TC-[A-Z]+-\d{3}) \| ([^'\"]+)", re.MULTILINE)
    for fname in os.listdir(specs_dir):
        if not fname.endswith('.spec.ts'):
            continue
        module = fname.replace('.spec.ts', '')
        with open(os.path.join(specs_dir, fname), 'r', encoding='utf-8') as f:
            content = f.read()
        for match in pattern.finditer(content):
            tc_id, scenario = match.groups()
            test_cases.append({'id': tc_id, 'module': module, 'scenario': scenario.strip()})
    return test_cases

def create_docx():
    doc = Document()
    # Cover page
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run('Ozone Mall Website – Software Testing Documentation')
    run.font.size = Pt(24)
    run.bold = True
    doc.add_paragraph('')
    # Project overview placeholder
    add_heading(doc, 'Project Overview', level=2)
    doc.add_paragraph('Provide a brief overview of the Ozone Mall website project. (Editable placeholder)')
    # Prepared by placeholders
    doc.add_paragraph('Prepared by: ____________________')
    doc.add_paragraph('Institution: ____________________')
    doc.add_paragraph('Date: ' + datetime.now().strftime('%Y-%m-%d'))
    doc.add_paragraph('Version: 1.0')
    doc.add_page_break()
    # Table of contents placeholder
    add_heading(doc, 'Table of Contents', level=1)
    doc.add_paragraph('Table of contents will be generated by Word (References → Table of Contents).')
    doc.add_page_break()
    # Introduction
    add_heading(doc, '1. Introduction', level=1)
    doc.add_paragraph('Background, purpose, website overview, testing objectives, scope and limitations.')
    # Test Plan
    add_heading(doc, '2. Test Plan', level=1)
    doc.add_paragraph('Testing scope, objectives, strategy, types, environment, tools, entry/exit criteria, roles, risks.')
    # Module‑wise Test Cases
    add_heading(doc, '3. Module‑wise Test Cases', level=1)
    test_cases = extract_test_cases()
    if test_cases:
        table = doc.add_table(rows=1, cols=4)
        hdr = table.rows[0].cells
        hdr[0].text = 'Test Case ID'
        hdr[1].text = 'Module'
        hdr[2].text = 'Scenario'
        hdr[3].text = 'Status'
        for tc in test_cases:
            row = table.add_row().cells
            row[0].text = tc['id']
            row[1].text = tc['module']
            row[2].text = tc['scenario']
            row[3].text = 'Not Executed'
    else:
        doc.add_paragraph('No test cases detected in source files.')
    # Test Execution Report
    add_heading(doc, '4. Test Execution Report', level=1)
    total = len(test_cases)
    doc.add_paragraph(f'Total test cases identified: {total}')
    doc.add_paragraph('Execution environment: Local Vite dev server (http://localhost:3000)')
    doc.add_paragraph('Execution date: ' + datetime.now().strftime('%Y-%m-%d'))
    doc.add_paragraph('Actual execution results: No automated run was performed (results.json missing). All test cases remain Not Executed.')
    # Bug Report
    add_heading(doc, '5. Bug Report', level=1)
    table = doc.add_table(rows=1, cols=12)
    hdr_titles = ['Bug ID','Test Case ID','Module','Title','Description','Steps To Reproduce','Expected','Actual','Severity','Priority','Status','Remarks']
    hdr = table.rows[0].cells
    for i, title in enumerate(hdr_titles):
        hdr[i].text = title
    doc.add_paragraph('No defects have been recorded yet.')
    # Regression Testing Report
    add_heading(doc, '6. Regression Testing Report', level=1)
    doc.add_paragraph('No regression testing performed because no failures were observed.')
    # Non‑Functional Testing
    add_heading(doc, '7. Non‑Functional Testing', level=1)
    doc.add_paragraph('Performance, accessibility, responsive design, browser compatibility, basic security and usability results have not been executed.')
    # Test Summary and Statistics
    add_heading(doc, '8. Test Summary and Statistics', level=1)
    doc.add_paragraph(f'Total test cases: {total}')
    doc.add_paragraph('Passed: 0')
    doc.add_paragraph('Failed: 0')
    doc.add_paragraph('Blocked: 0')
    doc.add_paragraph(f'Not Executed: {total}')
    # Recommendations and Future Improvements
    add_heading(doc, '9. Recommendations and Future Improvements', level=1)
    doc.add_paragraph('Provide actionable recommendations for quality improvement.')
    # Appendices
    add_heading(doc, '10. Appendices', level=1)
    doc.add_paragraph('Screenshots, test data, environment details, automation commands, references to test scripts.')
    # Save
    doc.save(report_docx_path)
    print('DOCX generated at', report_docx_path)

def create_pdf():
    c = canvas.Canvas(report_pdf_path, pagesize=A4)
    w, h = A4
    title = 'Ozone Mall Website – Software Testing Documentation'
    c.setFont('Helvetica-Bold', 18)
    c.drawCentredString(w/2, h-100, title)
    c.setFont('Helvetica', 12)
    c.drawString(50, h-150, f'Date: {datetime.now().strftime("%Y-%m-%d")}')
    c.drawString(50, h-170, 'Version: 1.0')
    c.drawString(50, h-200, 'This PDF contains the same high‑level sections as the Word document.')
    c.showPage()
    c.save()
    print('PDF generated at', report_pdf_path)

def create_csv_files():
    # Test Cases CSV (headers only)
    tc_path = os.path.join(base_dir, 'Detailed_Test_Cases.csv')
    with open(tc_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['Test_Case_ID','Module','Test_Scenario','Preconditions','Test_Data','Test_Steps','Expected_Result','Actual_Result','Status','Priority','Severity','Remarks'])
    # Bug Report CSV (headers only)
    bug_path = os.path.join(base_dir, 'Detailed_Bug_Report.csv')
    with open(bug_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['Bug_ID','Test_Case_ID','Module','Title','Description','Steps_To_Reproduce','Expected','Actual','Severity','Priority','Status','Screenshot_Path','Remarks'])
    print('CSV files created')

if __name__ == '__main__':
    create_docx()
    create_pdf()
    create_csv_files()
